// Build Node-loadable ESM entrypoints for package consumers in node_modules
// (Node refuses to type-strip .ts files inside node_modules).
import { chmod, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";

const root = fileURLToPath(new URL("..", import.meta.url));
const check = process.argv.includes("--check");

const targets = [
  { input: "src/vite.ts", output: "lib/vite.js", executable: false },
  { input: "src/fs-routes/js.ts", output: "lib/fs-routes.js", executable: false },
  { input: "src/fs-routes/routes.ts", output: "lib/fs-routes-cli.js", executable: true },
] as const;

for (const target of targets) {
  const bundle = await rolldown({
    input: path.join(root, target.input),
    platform: "node",
    external: [/^node:/],
  });
  const { output } = await bundle.generate({
    format: "es",
  });
  await bundle.close();

  const raw = output[0].code;
  const header = "// Generated by scripts/build-node.ts\n";
  const body = raw.startsWith("#!") ? raw.replace(/^#![^\n]*\n/, "") : raw;
  const source = `${target.executable ? "#!/usr/bin/env node\n" : ""}${header}${body}`;
  const outPath = path.join(root, target.output);

  if (check) {
    let existing: string;
    try {
      existing = await readFile(outPath, "utf8");
    } catch {
      throw new Error(`Missing ${target.output}. Run pnpm run build:node.`);
    }
    if (existing !== source) {
      throw new Error(`Out-of-date ${target.output}. Run pnpm run build:node.`);
    }
  } else {
    await mkdir(path.dirname(outPath), { recursive: true });
    await writeFile(outPath, source);
    if (target.executable) {
      await chmod(outPath, 0o755);
    }
  }
}
