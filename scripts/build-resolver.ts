// Embed the external browser asset for servers without filesystem access.
const result = await new Deno.Command(Deno.execPath(), {
  args: ["bundle", "--platform=browser", "--minify", "--quiet", "src/runtime/resolve.ts"],
  stdout: "piped",
}).output();
if (!result.success) throw new Error("Could not bundle the panel resolver.");
const js = new TextDecoder().decode(result.stdout).trim();
const file = new URL("../src/runtime/resolve-source.ts", import.meta.url);
const source = "// Generated by scripts/build-resolver.ts\n// deno-fmt-ignore-file\n" +
  "export const resolverSource = " + JSON.stringify(js) + ";\n";
if (Deno.args.includes("--check")) {
  if (await Deno.readTextFile(file) !== source) throw new Error("Run deno task resolver:build.");
} else {
  await Deno.writeTextFile(file, source);
}
